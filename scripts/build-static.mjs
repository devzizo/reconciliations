#!/usr/bin/env node
// Bundles public/ into src/generated/static.js so the Worker can serve the front end itself
// (wrangler.jsonc → build.command). Headers come from public/_headers.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pub = path.join(root, 'public');
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.json': 'application/json' };

const headers = {};
for (const line of fs.readFileSync(path.join(pub, '_headers'), 'utf8').split('\n')) {
  const m = /^\s+([A-Za-z-]+):\s*(.+)$/.exec(line);
  if (m) headers[m[1]] = m[2].trim();
}
const files = {};
for (const name of fs.readdirSync(pub)) {
  const ext = path.extname(name);
  if (!TYPES[ext]) continue;
  const body = fs.readFileSync(path.join(pub, name), 'utf8');
  files[`/${name}`] = { type: TYPES[ext], body, etag: `"${crypto.createHash('sha256').update(body).digest('hex').slice(0, 16)}"` };
}
fs.mkdirSync(path.join(root, 'src', 'generated'), { recursive: true });
fs.writeFileSync(path.join(root, 'src', 'generated', 'static.js'),
  `// Generated by scripts/build-static.mjs — do not edit.\nexport const STATIC_HEADERS = ${JSON.stringify(headers, null, 2)};\nexport const STATIC_FILES = ${JSON.stringify(files)};\n`);
console.log(`static: ${Object.keys(files).length} files`);
